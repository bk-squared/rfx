def test_the_required_job_names_still_exist() -> None:
    """Branch protection requires these contexts BY NAME.

    A rename leaves every required check permanently unreported and blocks every
    merge until someone edits branch protection, which is not visible from the
    repository.
    """
    jobs = load(PR_TESTS)["jobs"]
    for name in HEAVY_JOBS:
        assert name in jobs, f"pr-tests.yml no longer defines a `{name}` job"


def test_the_fast_suite_still_reports_six_groups_under_the_protected_names() -> None:
    fast = load(PR_TESTS)["jobs"]["fast-suite"]
    assert fast["strategy"]["matrix"]["group"] == [1, 2, 3, 4, 5, 6]
    # The 3.10 entry must render as `fast-suite (<group>)`; a plain matrix over
    # two python versions would render `fast-suite (3.10, 1)` and unreport every
    # required context.
    assert "format('fast-suite ({0})', matrix.group)" in fast["name"]


def test_the_changes_job_exists_and_publishes_the_verdict() -> None:
    jobs = load(PR_TESTS)["jobs"]
    assert "changes" in jobs, "pr-tests.yml has no `changes` job"
    outputs = jobs["changes"].get("outputs") or {}
    assert "code_changed" in outputs, outputs
    assert "steps.classify.outputs.code_changed" in outputs["code_changed"]


def test_the_changes_job_checks_out_full_history() -> None:
    """A shallow clone cannot find the merge base the diff is taken from."""
    steps = load(PR_TESTS)["jobs"]["changes"]["steps"]
    checkout = [s for s in steps if str(s.get("uses", "")).startswith("actions/checkout")]
    assert checkout, "the changes job does not check out the repository"
    assert checkout[0].get("with", {}).get("fetch-depth") == 0


def test_the_changes_job_delegates_to_the_tested_script() -> None:
    blocks = run_blocks(load(PR_TESTS)["jobs"]["changes"])
    assert any("scripts/ci/classify_changes.sh" in b for b in blocks), blocks


@pytest.mark.parametrize("job", HEAVY_JOBS)
def test_the_heavy_jobs_wait_for_the_verdict(job: str) -> None:
    needs = load(PR_TESTS)["jobs"][job].get("needs")
    needs = [needs] if isinstance(needs, str) else list(needs or [])
    assert "changes" in needs, f"`{job}` does not depend on `changes`"


@pytest.mark.parametrize("job", HEAVY_JOBS)
def test_every_step_after_checkout_is_gated_on_the_verdict(job: str) -> None:
    """The JOB always runs; only its steps are conditional.

    GitHub's "Troubleshooting required status checks" says a job skipped by a
    conditional reports Success, so a job-level `if:` would satisfy the required
    context too. Step level is still what this repo uses: a skipped job shows no
    steps and no reason, and an ungated step that installs the package or runs
    pytest would spend the 35 minutes the gate exists to save.
    """
    steps = load(PR_TESTS)["jobs"][job]["steps"]
    ungated = [
        step.get("name", step.get("uses", "?"))
        for step in steps[1:]
        if "needs.changes.outputs.code_changed" not in str(step.get("if", ""))
    ]
    assert not ungated, f"`{job}` steps run regardless of the verdict: {ungated}"


@pytest.mark.parametrize("job", HEAVY_JOBS)
def test_a_skipped_job_says_why_in_its_log(job: str) -> None:
    """A green job that did nothing has to explain itself, or it reads as a pass."""
    steps = load(PR_TESTS)["jobs"][job]["steps"]
    explainers = [
        step
        for step in steps
        if "code_changed == 'false'" in str(step.get("if", ""))
    ]
    assert len(explainers) == 1, f"`{job}` has {len(explainers)} explanation steps"
    assert "scripts/ci/changed_paths.py" in str(explainers[0].get("run", ""))


def test_pushes_to_main_still_trigger_the_lane() -> None:
    triggers = load(PR_TESTS).get("on", load(PR_TESTS).get(True))
    assert triggers["push"]["branches"] == ["main"]
    assert "pull_request" in triggers


