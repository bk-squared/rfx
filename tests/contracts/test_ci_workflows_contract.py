import sys
from pathlib import Path

import pytest
import yaml

REPO = Path(__file__).resolve().parents[2]
WORKFLOW_DIR = REPO / ".github" / "workflows"
PR_TESTS = WORKFLOW_DIR / "pr-tests.yml"
LINT = WORKFLOW_DIR / "lint.yml"
LOCAL_SH = REPO / "scripts" / "ci" / "local.sh"
RUNBOOK = REPO / "docs" / "agent" / "agent-runbook.mdx"
CLASSIFY_SH = REPO / "scripts" / "ci" / "classify_changes.sh"

_SPEC = importlib.util.spec_from_file_location(
    "changed_paths", REPO / "scripts" / "ci" / "changed_paths.py"
)
assert _SPEC is not None and _SPEC.loader is not None
changed_paths = importlib.util.module_from_spec(_SPEC)
sys.modules[_SPEC.name] = changed_paths
_SPEC.loader.exec_module(changed_paths)

HEAVY_JOBS = ("guards-and-preflight", "fast-suite")


def workflow_files() -> list[Path]:
    return sorted(WORKFLOW_DIR.glob("*.yml"))


def load(path: Path) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def run_blocks(node: object) -> list[str]:
    """Every `run:` script anywhere in a workflow document."""
    found: list[str] = []
    if isinstance(node, dict):
        for key, value in node.items():
            if key == "run" and isinstance(value, str):
                found.append(value)
            else:
                found += run_blocks(value)
    elif isinstance(node, list):
        for item in node:
            found += run_blocks(item)
    return found


