def _classify(env: dict[str, str], tmp_path: Path) -> tuple[str, str]:
    output = tmp_path / "github_output"
    output.touch()
    result = subprocess.run(
        ["bash", str(CLASSIFY_SH)],
        cwd=REPO,
        env={
            "PATH": os.environ.get("PATH", ""),
            "HOME": os.environ.get("HOME", "/tmp"),
            "GITHUB_OUTPUT": str(output),
            **env,
        },
        capture_output=True, text=True, timeout=120,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    return output.read_text(encoding="utf-8").strip(), result.stdout


def test_a_push_to_main_is_never_skipped(tmp_path: Path) -> None:
    """main is what releases, the GPU lane and the weekly suite are cut from."""
    written, log = _classify({"EVENT_NAME": "push"}, tmp_path)
    assert written == "code_changed=true", log


def test_a_diff_that_cannot_be_computed_runs_everything(tmp_path: Path) -> None:
    written, log = _classify(
        {"EVENT_NAME": "pull_request", "BASE_SHA": "not-a-sha", "HEAD_SHA": "HEAD"},
        tmp_path,
    )
    assert written == "code_changed=true", log


def test_a_missing_base_sha_runs_everything(tmp_path: Path) -> None:
    written, log = _classify({"EVENT_NAME": "pull_request"}, tmp_path)
    assert written == "code_changed=true", log
