_RUNBOOK_SENTENCE = "`scripts/ci/local.sh` runs, in order:"


def _local_sh_steps() -> list[str]:
    match = re.search(r"^STEP_NAMES=\(([^)]*)\)", LOCAL_SH.read_text(encoding="utf-8"), re.M)
    assert match, "scripts/ci/local.sh no longer declares STEP_NAMES=(...)"
    return match.group(1).split()


def _runbook_steps() -> list[str]:
    for line in RUNBOOK.read_text(encoding="utf-8").splitlines():
        if line.startswith(_RUNBOOK_SENTENCE):
            tail = line[len(_RUNBOOK_SENTENCE):].strip().rstrip(".")
            return [part.strip() for part in tail.split(",") if part.strip()]
    raise AssertionError(
        f"the runbook has no line starting {_RUNBOOK_SENTENCE!r} — authors are "
        "told to run a list that no longer exists"
    )


def test_local_sh_and_the_runbook_list_the_same_steps_in_the_same_order() -> None:
    assert _local_sh_steps() == _runbook_steps()


def test_local_sh_runs_the_real_entry_points() -> None:
    """Not a re-implementation: the same files CI calls."""
    text = LOCAL_SH.read_text(encoding="utf-8")
    for entry_point in (
        "scripts/ci/lint.sh",
        "scripts/ci/docs_hygiene.sh",
        "scripts/changelog/assemble.py --check",
        "scripts/ci/check_pr_body.py --file",
        "pytest tests/contracts",
    ):
        assert entry_point in text, f"scripts/ci/local.sh no longer runs {entry_point}"


def test_the_runbook_tells_authors_to_run_it_before_every_push() -> None:
    text = RUNBOOK.read_text(encoding="utf-8")
    assert "run `scripts/ci/local.sh` before every push" in text


