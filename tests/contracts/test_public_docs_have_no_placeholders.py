"""Keep pages in the site's navigation useful to readers.

A page must not be a skeleton or carry an unfinished marker or tracker number.
Headings and code examples need content, and internal links need a destination.
Navigation labels must also be free of unfinished markers.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from urllib.parse import unquote, urlsplit

import pytest

REPO = Path(__file__).resolve().parents[2]
PUBLIC = REPO / "docs/public"
MAP_SOURCE = (PUBLIC / "site_map.json").read_text(encoding="utf-8")
GROUPS = json.loads(MAP_SOURCE)["groups"]
SLUGS = {slug for group in GROUPS for slug in group["items"]}
TRACKER_EXEMPTIONS = {
    "rfx/project/changelog": "a changelog cites the PR of each entry",
}
# These routes are generated by the docs bundle rather than authored pages.
GENERATED_ROUTE_PREFIXES = (
    "rfx/api/generated/", "rfx/markdown/", "rfx/llms.txt", "rfx/llms-full.txt",
    "rfx/docs-manifest.json", "rfx/api/inventory.json", "rfx/api/support/",
    "rfx/versions/",
)
MARKER = re.compile(
    r"(?i:Being\s+written|Being\s+restructured|Being\s+merged|Pending\s+for\s+2\.0|coming\s+soon)"
    r"|\b(?:TODO|TBD|FIXME)\b"
)
TRACKER = re.compile(
    # A wrapped reference may cross one line, but never a blank paragraph.
    # After "#" any number counts (rfx has issues #40-#80); without "#", three to five digits
    # (so "issue 3" of a journal does not).
    r"\b(?:tracker|issue|PR|pull[ \t]+request)(?:(?:[ \t]+(?:\n[ \t]*)?|\n[ \t]*)?#\d+"
    r"|(?:[ \t]+(?:\n[ \t]*)?|\n[ \t]*)\d{3,5})\b|\brfx#\d+\b|\bgh-\d{3,5}\b"
    r"|(?<![\w&/])#\d{3,5}\b"
    r"|(?:https?://)?github\.com/bk-squared/rfx/(?:issues|pull)/\d+\b",
    re.IGNORECASE,
)
FENCE = re.compile(r"^[ \t]*(`{3,}|~{3,})(.*)$")
HEADING = re.compile(r"^[ \t]{0,3}(#{1,6})(?:[ \t]+|$)")
COMMENT = re.compile(r"\{/\*.*?(?:\*/\}|\Z)", re.DOTALL)
FRONTMATTER = re.compile(r"\A---[ \t]*\n.*?\n---[ \t]*(?:\n|$)", re.DOTALL)
INLINE_CODE = re.compile(r"(?<!`)(`+)(?!`).*?(?<!`)\1(?!`)", re.DOTALL)
TAG = re.compile(r"</?[A-Za-z][\w:.-]*(?:[^<>\"']|\"[^\"]*\"|'[^']*')*>", re.DOTALL)
ATTRIBUTE = re.compile(r"(?<![\w:-])([\w:-]+)\s*=\s*(\"[^\"]*\"|'[^']*'|[^\s>]+)")
LINK = re.compile(r"\]\(\s*(/rfx/[^\s)]+)")


def blank(text: str) -> str:
    """Hide syntax without moving subsequent source locations."""
    return re.sub(r"[^\n]", " ", text)


def resolve_slug(slug: str) -> Path:
    rel = "index" if slug == "rfx" else slug.removeprefix("rfx/")
    candidates = [PUBLIC / f"{rel}{suffix}" for suffix in (".md", ".mdx", "/index.md", "/index.mdx")]
    return next((path for path in candidates if path.is_file()), candidates[0])


def prose_and_blocks(source: str) -> tuple[str, str, list[int]]:
    """Separate fenced examples, preserving comments inside their code."""
    frontmatter = FRONTMATTER.match(source)
    visible = list(blank(frontmatter[0]) + source[frontmatter.end():]
                   if frontmatter else source)
    fence = None
    comment = False
    empty_blocks = []
    content = []
    opening = 0
    offset = 0
    headings = []
    for line in source.splitlines(keepends=True):
        if fence is not None:
            stripped = line.strip()
            if len(stripped) >= len(fence) and set(stripped) == {fence[0]}:
                if not "".join(content).strip():
                    empty_blocks.append(opening)
                fence = None
            else:
                content.append(line)
            shown = blank(line)
            heading_line = blank(line)
        else:
            chars = list("".join(visible[offset:offset + len(line)]))
            index = 0
            while index < len(line):
                if not comment and line.startswith("{/*", index):
                    comment = True
                if comment:
                    if line.startswith("*/}", index):
                        chars[index:index + 3] = "   "
                        index += 3
                        comment = False
                        continue
                    chars[index] = "\n" if line[index] == "\n" else " "
                index += 1
            shown = "".join(chars)
            heading_line = shown
            match = FENCE.match(shown)
            if match:
                fence = match[1]
                opening = offset
                content = []
                shown = blank(shown)
                # A fence is body content for the preceding heading.
        visible[offset:offset + len(line)] = shown
        headings.append(heading_line)
        offset += len(line)
    return "".join(visible), "".join(headings), empty_blocks


def page_findings(slug: str, source: str) -> list[str]:
    findings = []
    lines = source.splitlines()

    def report(kind: str, offset: int) -> None:
        number = source.count("\n", 0, offset) + 1
        findings.append(f"{slug}:{number}: {kind}: {lines[number - 1]}")

    for match in MARKER.finditer(source):
        report("D1 unfinished marker", match.start())
    prose, headings, empty_blocks = prose_and_blocks(source)
    pending = None
    offset = 0
    for line in headings.splitlines(keepends=True):
        heading = HEADING.match(line)
        if heading:
            level = len(heading[1])
            if pending is not None and level <= pending[0]:
                report("D2 heading without body", pending[1])
            pending = (level, offset)
        elif line.strip():
            pending = None
        offset += len(line)
    if pending is not None:
        report("D2 heading without body", pending[1])
    for offset in empty_blocks:
        report("D4 empty fenced code block", offset)

    prose = INLINE_CODE.sub(lambda match: blank(match[0]), prose)
    links = [(match.start(1), match[1]) for match in LINK.finditer(prose)]

    def mask_attributes(tag: re.Match) -> str:
        def attribute(match: re.Match) -> str:
            name, value = match[1].lower(), match[2]
            if name in {"href", "src"}:
                links.append((tag.start() + match.start(2), value.strip("\"'")))
            return match[0] if name == "href" else blank(match[0])
        return ATTRIBUTE.sub(attribute, tag[0])

    prose = TAG.sub(mask_attributes, prose)
    if slug not in TRACKER_EXEMPTIONS:
        for match in TRACKER.finditer(prose):
            report("D3 tracker/issue/PR reference", match.start())
    for offset, target in links:
        if not target.startswith("/rfx/"):
            continue
        route = unquote(urlsplit(target).path).lstrip("/")
        if route.rstrip("/") in SLUGS or route.startswith(GENERATED_ROUTE_PREFIXES):
            continue
        asset = (PUBLIC / route.removeprefix("rfx/")).resolve()
        if asset.is_relative_to(PUBLIC.resolve()) and asset.is_file():
            continue
        report("D5 unresolved internal link", offset)
    return findings


@pytest.mark.reads_docs_for_gate(reason=(
    "Public navigation must not publish skeleton pages, unfinished markers, tracker references, "
    "empty examples or broken internal links (leader's placeholder gate, 2026-10-21)."))
@pytest.mark.parametrize("slug", sorted(SLUGS), ids=str)
def test_public_docs_have_no_placeholders(slug: str) -> None:
    path = resolve_slug(slug)
    assert path.is_file(), f"{slug}:1: D5 missing navigation page: {path}"
    findings = page_findings(slug, path.read_text(encoding="utf-8"))
    assert not findings, "\n" + "\n".join(findings)


@pytest.mark.parametrize("group", GROUPS, ids=lambda group: group["label"])
def test_navigation_labels_have_no_placeholders(group: dict) -> None:
    label = group["label"]
    offset = MAP_SOURCE.index(json.dumps(label, ensure_ascii=False))
    number = MAP_SOURCE.count("\n", 0, offset) + 1
    assert not MARKER.search(label), f"site_map.json:{number}: D1 unfinished group label: {label}"


def test_tracker_exemptions_are_in_navigation() -> None:
    assert TRACKER_EXEMPTIONS.keys() <= SLUGS
    assert all(TRACKER_EXEMPTIONS.values())


@pytest.mark.parametrize(("source", "kinds"), [
    ('---\ntitle: Example\n---\n## Empty\n{/* comment\n*/}\n## Next\nBody', {"D2"}),
    ('## Parent\n### Child\nBody\n', set()),
    ('  ~~~text\n## Example\ntracker 1234\n  ~~~\n', set()),
    ('```\n \t\n```\n', {"D4"}),
    ('{/* TODO tracker 1171 */}\n', {"D1"}),
    ('<p style="color: #333" data-note="issue 1332">Safe &#123; /#1332</p>', set()),
    ('`tracker 1171` and ``PR #1337 ` nested``', set()),
    ('<a href="https://github.com/bk-squared/rfx/issues/1">Details</a>', {"D3"}),
    ('tracker #1171; issue 1332; PR 1716; pull request 1337; #1332; rfx#1315', {"D3"}),
    ('[Missing](/rfx/nonexistent-contract-target/?x=1#part)', {"D5"}),
    ('<img src="/rfx/nonexistent-contract-target.png" />', {"D5"}),
    ('[Install](/rfx/start/install/?x=1#part)', set()),
    ('## Open a pull request\n\n1. Fork the repository.', set()),
    ('A wrapped tracker\n1171 reference.', {"D3"}),
    ('PR#1716, issue#1332 and gh-1171', {"D3"}),
    ('See issue #44 and PR #72.', {"D3"}),
    ('IEEE Trans. Microw. Theory Techn., vol. 70, issue 3, 2022', set()),
    ('issue1332 and tracker1171 are identifiers.', set()),
    ('## Empty\n{/* ```\ncomment only\n*/}\n', {"D2"}),
    ('## Example\n```text\n{/* tracker 1171 */}\n```\n', set()),
    ('<p data-note="Being written">Body</p>\n{/* FIXME */}', {"D1"}),
    ('[Generated](/rfx/api/generated/rfx.html#module)', set()),
    ('<a href="/rfx/start/install/">Install</a>', set()),
])
def test_placeholder_detection(source: str, kinds: set[str]) -> None:
    found = page_findings("rfx/test", source)
    assert {finding.split(": ")[1].split()[0] for finding in found} == kinds
