"""Synthetic box coefficient precision and original float32 bit patterns."""
from pathlib import Path
import sys
import warnings
from unittest.mock import patch

import jax
import numpy as np
import pytest

from tests.contracts.path_equivalence.builders import build


def solve(entry, precision):
    import rfx.stepping.graded_loop as loop
    states = []
    assemble = loop._assemble_nu_result

    def capture(setup, final, *args, **kwargs):
        states.append(final['fdtd'])
        return assemble(setup, final, *args, **kwargs)

    lane = 'run_nonuniform' if entry == 'run' else 'fwd_nonuniform'
    sim = build(('_materials', 'eps'), lane, graded=True, precision=precision)
    assert any(np.ptp(p) > 0 for p in (sim._dx_profile, sim._dy_profile, sim._dz_profile))
    with patch.object(loop, '_assemble_nu_result', capture):
        result = (sim.run(n_steps=36, compute_s_params=False, skip_preflight=True) if entry == 'run'
                  else sim.forward(n_steps=36, checkpoint=False, skip_preflight=True))
    return result, states[-1]


@pytest.mark.parametrize('entry', ('run', 'forward'))
def test_float32_bitwise_original(entry):
    # Generated by running git archive 95e66c479 on the Mac: B1 dielectric
    # box, graded=True (0.9/1.1 cell pair on each axis), explicit float32,
    # 36 steps, checkpoint=False. Only six final fields and probes are stored.
    reference = Path(__file__).with_name('graded_float32_95e66c479.npz')
    try:
        with jax.enable_x64(False), warnings.catch_warnings(), np.load(reference) as expected:
            warnings.simplefilter('ignore', UserWarning)
            result, state = solve(entry, 'float32')
            jax.block_until_ready(result.time_series)
            for name in ('ex', 'ey', 'ez', 'hx', 'hy', 'hz', 'time_series'):
                actual = np.asarray(result.time_series if name == 'time_series' else getattr(state, name))
                assert actual.dtype == np.float32
                np.testing.assert_array_equal(actual.view(np.uint32), expected[f'{entry}_{name}'],
                                              err_msg=f'B6 {entry}.{name} differs from 95e66c479')
    finally:
        jax.clear_caches()


@pytest.mark.parametrize('entry', ('run', 'forward'))
def test_float64_step_coefficients(entry):
    from rfx.stepping import yee
    from rfx.boundaries import cpml
    observed = set()
    codes = {yee.update_e_nu.__code__: ('E', ('ca_x', 'ca_y', 'ca_z', 'cb_x', 'cb_y', 'cb_z')),
             yee.update_h_nu.__code__: ('H', ('ch_x', 'ch_y', 'ch_z')),
             cpml.apply_cpml_e.__code__: ('CPML E', ('_ce_ex', '_ce_ey', '_ce_ez')),
             cpml.apply_cpml_h.__code__: ('CPML H', ('ch',))}

    def inspect_coefficients(frame, event, arg):
        # Read the coefficients the actual traced update used, not a second
        # calculation in the test. Return events retain the update's locals.
        if event == 'return' and frame.f_code in codes:
            half, names = codes[frame.f_code]
            for name in names:
                for value in jax.tree.leaves(frame.f_locals[name]):
                    assert value.dtype == np.float64, f'B2 {entry} {half}.{name} dtype {value.dtype}; expected float64'
            observed.add(half)

    previous = sys.getprofile()
    try:
        with jax.enable_x64(True), warnings.catch_warnings():
            warnings.simplefilter('ignore', UserWarning)
            sys.setprofile(inspect_coefficients)
            result, _ = solve(entry, 'float64')
            jax.block_until_ready(result.time_series)
            assert observed == {'E', 'H', 'CPML E', 'CPML H'}, observed
    finally:
        sys.setprofile(previous)
        jax.clear_caches()
