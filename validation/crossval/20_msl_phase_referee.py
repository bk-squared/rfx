def _build_stage_a_notch_tutorial(ContinuousStructure, openEMS, MSLPort, *,
                                  nrts: int | None, end_criteria: float | None):
    """Build MSL_NotchFilter.py's geometry fresh (smoke + real run, matching
    the coax/thru precedent's "separate openEMS instances" pattern)."""
    kw = {}
    if nrts is not None:
        kw["NrTS"] = nrts
    if end_criteria is not None:
        kw["EndCriteria"] = end_criteria
    fdtd = openEMS(**kw)
    fdtd.SetGaussExcite(A_F_MAX_HZ / 2.0, A_F_MAX_HZ / 2.0)
    fdtd.SetBoundaryCond(["PML_8", "PML_8", "MUR", "MUR", "PEC", "MUR"])

    csx = ContinuousStructure()
    fdtd.SetCSX(csx)
    mesh = csx.GetGrid()
    mesh.SetDeltaUnit(A_UNIT)

    resolution = _C0 / (A_F_MAX_HZ * np.sqrt(A_SUBSTRATE_EPR)) / A_UNIT / 50.0
    third_mesh = np.array([2.0 * resolution / 3.0, -resolution / 3.0]) / 4.0

    mesh.AddLine("x", [0.0])
    mesh.AddLine("x", A_MSL_WIDTH_UM / 2.0 + third_mesh)
    mesh.AddLine("x", -A_MSL_WIDTH_UM / 2.0 - third_mesh)
    mesh.SmoothMeshLines("x", resolution / 4.0)
    mesh.AddLine("x", [-A_MSL_LENGTH_UM, A_MSL_LENGTH_UM])
    mesh.SmoothMeshLines("x", resolution)

    mesh.AddLine("y", [0.0])
    mesh.AddLine("y", A_MSL_WIDTH_UM / 2.0 + third_mesh)
    mesh.AddLine("y", -A_MSL_WIDTH_UM / 2.0 - third_mesh)
    mesh.SmoothMeshLines("y", resolution / 4.0)
    mesh.AddLine("y", [-15.0 * A_MSL_WIDTH_UM, 15.0 * A_MSL_WIDTH_UM + A_STUB_LENGTH_UM])
    mesh.AddLine("y", (A_MSL_WIDTH_UM / 2.0 + A_STUB_LENGTH_UM) + third_mesh)
    mesh.SmoothMeshLines("y", resolution)

    mesh.AddLine("z", np.linspace(0.0, A_SUBSTRATE_THICKNESS_UM, 5))
    mesh.AddLine("z", [3000.0])
    mesh.SmoothMeshLines("z", resolution)

    substrate = csx.AddMaterial("RO4350B", epsilon=A_SUBSTRATE_EPR)
    substrate.AddBox(
        [-A_MSL_LENGTH_UM, -15.0 * A_MSL_WIDTH_UM, 0.0],
        [A_MSL_LENGTH_UM, 15.0 * A_MSL_WIDTH_UM + A_STUB_LENGTH_UM, A_SUBSTRATE_THICKNESS_UM],
    )

    pec = csx.AddMetal("PEC")
    port0 = MSLPort(
        csx, port_nr=1, metal_prop=pec,
        start=[-A_MSL_LENGTH_UM, -A_MSL_WIDTH_UM / 2.0, A_SUBSTRATE_THICKNESS_UM],
        stop=[0.0, A_MSL_WIDTH_UM / 2.0, 0.0],
        prop_dir="x", exc_dir="z", excite=-1.0,
        FeedShift=10.0 * resolution, MeasPlaneShift=A_MSL_LENGTH_UM / 3.0,
        priority=10,
    )
    port1 = MSLPort(
        csx, port_nr=2, metal_prop=pec,
        start=[A_MSL_LENGTH_UM, -A_MSL_WIDTH_UM / 2.0, A_SUBSTRATE_THICKNESS_UM],
        stop=[0.0, A_MSL_WIDTH_UM / 2.0, 0.0],
        prop_dir="x", exc_dir="z",
        MeasPlaneShift=A_MSL_LENGTH_UM / 3.0,
        priority=10,
    )

    pec.AddBox(
        [-A_MSL_WIDTH_UM / 2.0, A_MSL_WIDTH_UM / 2.0, A_SUBSTRATE_THICKNESS_UM],
        [A_MSL_WIDTH_UM / 2.0, A_MSL_WIDTH_UM / 2.0 + A_STUB_LENGTH_UM, A_SUBSTRATE_THICKNESS_UM],
        priority=10,
    )
    return fdtd, port0, port1


def _run_stage_a_reproduce_gate(*, sim_root: str, threads: int) -> dict:
    ContinuousStructure, openEMS, MSLPort = _import_openems()

    sim_dir = os.path.join(sim_root, "stage_a_notch_tutorial")
    smoke_dir = os.path.join(sim_root, "stage_a_notch_tutorial_smoke")

    smoke_fdtd, _p0, _p1 = _build_stage_a_notch_tutorial(
        ContinuousStructure, openEMS, MSLPort, nrts=200, end_criteria=0.0)
    smoke_log = _run_openems_capturing_stdout(smoke_fdtd, smoke_dir, threads=threads)
    _scan_stdout_for_bad_patterns(smoke_log, "stage_a_smoke")

    # Tutorial's own defaults (NrTS~=1e9, EndCriteria=1e-5) -- verbatim,
    # not overridden (module docstring STAGE A).
    fdtd, port0, port1 = _build_stage_a_notch_tutorial(
        ContinuousStructure, openEMS, MSLPort, nrts=None, end_criteria=None)

    t0 = time.time()
    real_log = _run_openems_capturing_stdout(fdtd, sim_dir, threads=threads)
    _scan_stdout_for_bad_patterns(real_log, "stage_a", check_truncation=True)
    elapsed = time.time() - t0

    freqs = np.linspace(1.0e6, A_F_MAX_HZ, A_N_FREQS)
    port0.CalcPort(sim_dir, freqs)
    port1.CalcPort(sim_dir, freqs)

    inc_peak, n_samples = _check_excitation_and_trace(port0, sim_dir, "stage_a")
    # D3 fix (run-1 forensics, review 2026-08-04): NrTS defaults to ~1e9 so a
    # probe-row-count-vs-NrTS comparison (n_samples never approaches ~1e9)
    # could never fire -- read the ACTUAL log-reported truncation signal
    # instead (the SAME "reached before the end-criteria of" text
    # _run_stage_b's own end_criteria_not_reached checks, now visible after
    # the fd-2 capture fix). Run-1 ground truth: Stage A's real run reached
    # its own EndCriteria=1e-5 (-50dB) -- this reads False on that data,
    # correctly, for the right reason (log content), not by construction.
    truncated_suspected = _log_indicates_truncation(real_log)

    s11 = np.asarray(port0.uf_ref, dtype=np.complex128) / np.asarray(port0.uf_inc, dtype=np.complex128)
    s21 = np.asarray(port1.uf_ref, dtype=np.complex128) / np.asarray(port0.uf_inc, dtype=np.complex128)
    _non_physical_guard(np.abs(s11), "stage_a_s11")
    _non_physical_guard(np.abs(s21), "stage_a_s21")

    s21_db = 20.0 * np.log10(np.abs(s21) + 1e-30)
    # Search only the physically-plausible window around the analytic
    # estimate (avoids a spurious minimum elsewhere in the 1601-point,
    # 7 GHz sweep).
    search_lo, search_hi = 0.5 * F_NOTCH_AN_HZ, 1.5 * F_NOTCH_AN_HZ
    search_mask = (freqs >= search_lo) & (freqs <= search_hi)
    if not np.any(search_mask):
        search_mask = np.ones_like(freqs, dtype=bool)
    i_local = int(np.argmin(s21_db[search_mask]))
    f_notch = float(freqs[search_mask][i_local])
    notch_depth_db = float(s21_db[search_mask][i_local])

    gate = REPRODUCE_GATE_RECORD["gate"]
    f_notch_ok = bool(gate["f_notch_lo_hz"] <= f_notch <= gate["f_notch_hi_hz"])

    # Symmetry fix (#552 reviewer follow-up): Stage B's own sanity_passed
    # consults truncated/end_criteria_not_reached; Stage A's passed did not
    # consult truncated_suspected at all, so a truncated real run (NrTS cap
    # hit before EndCriteria) would still report passed=True and let a
    # truncated notch-frequency measurement through as a reproduce-gate
    # PASS. Low risk in practice (Stage A's real run uses the tutorial's
    # own defaults, NrTS~=1e9, so truncation is unreachable on any run that
    # completes in a sane wall-clock budget) but not structurally
    # impossible, and Stage B already treats it as gating.
    passed = bool(f_notch_ok and not truncated_suspected)
    return {
        "freqs_hz": freqs.tolist(),
        "s11_mag": np.abs(s11).tolist(), "s21_mag": np.abs(s21).tolist(),
        "f_notch_hz": f_notch, "notch_depth_db": notch_depth_db,
        "f_notch_expected_hz": float(F_NOTCH_AN_HZ),
        "f_notch_dev_pct": abs(f_notch - F_NOTCH_AN_HZ) / F_NOTCH_AN_HZ * 100.0,
        "f_notch_ok": f_notch_ok,
        "max_uf_inc": inc_peak, "n_trace_samples": n_samples,
        "truncated_suspected": truncated_suspected, "elapsed_s": round(elapsed, 1),
        "passed": passed,
    }


