def _assert_matches_rfx_fixture(fixture: dict) -> None:
    """Drift guard: this script's OWN Stage B constants must match the
    committed fixture's ``meta`` block. A mismatch is a CONFIG bug (exit
    3), not a physics finding -- it means the two sides silently stopped
    describing the same geometry.
    """
    meta = fixture["meta"]
    checks = [
        ("eps_r", meta["eps_r"], B_EPS_R),
        ("h_sub_m", meta["h_sub_m"], B_H_SUB_M),
        ("w_trace_m", meta["w_trace_m"], B_W_TRACE_M),
        ("l_line_m", meta["l_line_m"], B_L_LINE_M),
        ("port_margin_m", meta["port_margin_m"], B_PORT_MARGIN_M),
        ("dx_m", meta["dx_m"], B_DX_M),
        ("f_max_hz", meta["f_max_hz"], B_F_MAX_HZ),
    ]
    for name, fixture_val, local_val in checks:
        assert abs(float(fixture_val) - float(local_val)) < 1e-12 * max(1.0, abs(local_val)), (
            f"Stage B constant {name!r} drifted from the committed rfx "
            f"fixture: script={local_val!r} fixture={fixture_val!r}. "
            f"Regenerate the fixture or update the script constants."
        )


def _stage_b_layout(fixture: dict) -> dict:
    """Pure arithmetic (openEMS-free, testable without the solver): every
    Stage B position/ref_plane_shift, in metres. An AssertionError here is
    a config bug (exit 3), matching the coax lane's ``_stage_b_layout``
    convention.
    """
    _assert_matches_rfx_fixture(fixture)
    geom = fixture["reference_plane_geometry"]
    grid = geom["_grid"]

    lx_clear_m = grid["rasterized_clear_m"]["x"]
    ly_clear_m = grid["rasterized_clear_m"]["y"]
    lz_clear_m = grid["rasterized_clear_m"]["z"]
    pml_x_m = grid["pad_x_lo"] * grid["dx"]
    pml_y_m = grid["pad_y_lo"] * grid["dx"]
    pml_z_hi_m = grid["pad_z_hi"] * grid["dx"]

    p0 = geom["msl_0"]
    p1 = geom["msl_1"]
    assert p0["direction"] == "+x" and p1["direction"] == "-x", (
        "unexpected port direction in the committed rfx fixture"
    )

    def _ref_plane_shift(port_geom: dict) -> float:
        direction = 1.0 if port_geom["direction"] == "+x" else -1.0
        return (port_geom["probe0_x_m"] - port_geom["feed_x_m"]) * direction

    ref_plane_shift_port0_m = _ref_plane_shift(p0)
    ref_plane_shift_port1_m = _ref_plane_shift(p1)
    l12_m = abs(p1["probe0_x_m"] - p0["probe0_x_m"])

    layout = {
        "lx_clear_m": lx_clear_m, "ly_clear_m": ly_clear_m, "lz_clear_m": lz_clear_m,
        "pml_x_m": pml_x_m, "pml_y_m": pml_y_m, "pml_z_hi_m": pml_z_hi_m,
        "feed_x_port0_m": p0["feed_x_m"], "feed_x_port1_m": p1["feed_x_m"],
        "probe0_x_port0_m": p0["probe0_x_m"], "probe0_x_port1_m": p1["probe0_x_m"],
        "ref_plane_shift_port0_m": ref_plane_shift_port0_m,
        "ref_plane_shift_port1_m": ref_plane_shift_port1_m,
        "l12_m": l12_m,
    }

    # Config assertions (a regression here is a script bug, exit 3).
    assert lx_clear_m > 0 and ly_clear_m > 0 and lz_clear_m > 0
    assert 0.0 < p0["feed_x_m"] < p1["feed_x_m"] < lx_clear_m, (
        "Stage B port ordering broken (port0 must sit left of port1)"
    )
    assert p0["probe0_x_m"] < p1["probe0_x_m"], (
        "Stage B probe-0 ordering broken"
    )
    port_w_m = B_PORT_W_CELLS * B_DX_M
    assert port_w_m < abs(p1["feed_x_m"] - p0["feed_x_m"]) / 2.0, (
        "Stage B port span too long relative to the feed-to-feed gap "
        "(ports would overlap at line centre)"
    )
    return layout


