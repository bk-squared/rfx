def _stage_b_substrate_z_mesh(h_sub: float, dx: float) -> tuple[np.ndarray, int]:
    """m6 fix: an explicit mesh line AT the substrate top (the openEMS
    MSL_NotchFilter.py tutorial's own ``linspace(0, substrate_thickness,
    5)`` pattern), instead of leaving the substrate top wherever a plain
    uniform ``np.arange`` from z=0 happens to land -- the #325
    rasterization class (intended vs ACTUAL cell count silently
    disagreeing; rfx's own do-not-repeat here covered dx choice, not
    z-line PLACEMENT). Builds a uniform sub-mesh spanning EXACTLY
    [0, h_sub] with ``round(h_sub/dx)`` cells (5 at this fixture's own
    h_sub=254um/dx=50um -- NOT an even divisor, so each substrate cell is
    ~50.8um, not exactly dx -- redistributing the mismatch across the
    substrate instead of leaving one arbitrary sliver cell wherever an
    unguided arange happened to cross z=h_sub).

    Pure arithmetic, openEMS-free -- testable directly (see the header
    test's own rasterized-substrate-cell-count pin).
    """
    n_sub = max(1, round(h_sub / dx))
    z_lines_sub = np.linspace(0.0, h_sub, n_sub + 1)
    return z_lines_sub, n_sub


def _predict_measplane_snap(target_shift_m: float, dx_m: float) -> float:
    """Predict what ``MSLPort.__init__``'s own mesh-line snap will compute
    for ``measplane_shift``, given a UNIFORM x-mesh at step ``dx_m`` (Stage
    B's own x-mesh has no thirds-rule refinement, unlike y -- see
    ``_build_stage_b``). openEMS's own snap (``python/openEMS/ports.py``,
    fetched 2026-08-04): ``meas_pos_idx = argmin(abs(prop_lines -
    measplane_pos))`` then ``measplane_shift = abs(start - prop_lines[
    meas_pos_idx])`` -- on a uniform grid whose own ``start`` already sits
    exactly on a mesh line (true for this fixture's own feed_x0/feed_x1,
    both integer multiples of dx_m from the mesh origin), this is exactly
    rounding ``target_shift_m`` to the nearest integer multiple of
    ``dx_m``. Pure arithmetic, openEMS-free -- ``_build_stage_b`` (VESSL-
    only, openEMS required) cross-checks the REAL, measured ``port.
    measplane_shift`` against this prediction at build time, so a future
    mesh change that breaks the "uniform, start-aligned grid" assumption
    this function relies on fails loud (an AssertionError), not silently.
    """
    n_cells = round(target_shift_m / dx_m)
    return n_cells * dx_m


def _stage_b_port_placement(layout: dict) -> dict:
    """Pure arithmetic (openEMS-free): the trace span, each port's target
    MeasPlaneShift/ref_plane_shift, and a PREDICTION of the resulting
    EFFECTIVE CalcPort shift (``ref_plane_shift - measplane_shift``).
    ``_build_stage_b`` calls this directly for its own AddBox/
    MeasPlaneShift values (wired, not a second hand-copy) and returns both
    this prediction AND the REAL, openEMS-measured values for the caller
    to record.

    NEW-1 finding (review 2026-08-04, the one that matters): on the
    COMMITTED fixture, ``ref_plane_shift`` and the predicted
    ``measplane_shift`` are IDENTICAL (both land on an EXISTING mesh line
    -- dx=50um divides the 2.5mm target exactly, 50 cells), so the
    predicted ``effective_shift`` is 0.0. ``CalcPort``'s own TL-phase-
    rotation (``python/openEMS/ports.py``, base ``Port.CalcPort``:
    ``phase = real(beta)*shift; uf_tot' = uf_tot*cos(-phase) + ...``) is
    therefore a NO-OP on THIS specific fixture -- the phase-plane
    correctness this referee measures comes from ``MeasPlaneShift``'s own
    STENCIL PLACEMENT landing exactly at rfx's own probe-0 plane, not from
    the referral ROTATION actually correcting a nonzero offset. The
    ``ref_plane_shift`` argument is still passed to ``CalcPort`` (the code
    path exists and is exercised, computing and applying a shift of
    0.0 -- not skipped), and remains the correct, necessary mechanism for
    a geometry where the target plane does NOT happen to fall exactly on
    a pre-existing mesh line; this fixture's own placement was chosen
    (m5 fix) specifically so it WOULD land exactly on-grid, which is what
    makes the shift trivial here. See DECLARED_QUESTION / module
    docstring CONVENTION NOTE for the full, non-overclaiming statement.
    """
    trace_x_start_m = layout["feed_x_port0_m"]
    trace_x_stop_m = layout["feed_x_port1_m"]
    ref_shift0_m = layout["ref_plane_shift_port0_m"]
    ref_shift1_m = layout["ref_plane_shift_port1_m"]
    measplane_predicted0_m = _predict_measplane_snap(ref_shift0_m, B_DX_M)
    measplane_predicted1_m = _predict_measplane_snap(ref_shift1_m, B_DX_M)
    return {
        "trace_x_start_m": trace_x_start_m,
        "trace_x_stop_m": trace_x_stop_m,
        "ref_plane_shift_port0_m": ref_shift0_m,
        "ref_plane_shift_port1_m": ref_shift1_m,
        # The value passed as the MeasPlaneShift= kwarg (m5 fix): the
        # SAME target ref_plane_shift is aimed for directly.
        "measplane_shift_target_port0_m": ref_shift0_m,
        "measplane_shift_target_port1_m": ref_shift1_m,
        "measplane_shift_predicted_port0_m": measplane_predicted0_m,
        "measplane_shift_predicted_port1_m": measplane_predicted1_m,
        "effective_shift_predicted_port0_m": ref_shift0_m - measplane_predicted0_m,
        "effective_shift_predicted_port1_m": ref_shift1_m - measplane_predicted1_m,
    }


def _build_stage_b(ContinuousStructure, openEMS, MSLPort, layout: dict, *,
                   nrts: int, end_criteria: float):
    unit = 1.0e-6  # um, independent CSXCAD unit choice for Stage B
    dx = B_DX_M / unit

    lx_clear = layout["lx_clear_m"] / unit
    ly_clear = layout["ly_clear_m"] / unit
    lz_clear = layout["lz_clear_m"] / unit
    pml_x = layout["pml_x_m"] / unit
    pml_y = layout["pml_y_m"] / unit
    pml_z_hi = layout["pml_z_hi_m"] / unit

    # z_lo is PEC, no padding below (matches rfx pad_z_lo=0).
    x0, x1 = -pml_x, lx_clear + pml_x
    y0, y1 = -pml_y, ly_clear + pml_y
    z1 = lz_clear + pml_z_hi  # z=0 is the PEC ground plane (z_lo, no padding)

    y_centre = ly_clear / 2.0
    w_trace = B_W_TRACE_M / unit
    h_sub = B_H_SUB_M / unit
    trace_y_lo = y_centre - w_trace / 2.0
    trace_y_hi = y_centre + w_trace / 2.0

    fdtd = openEMS(NrTS=nrts, EndCriteria=end_criteria)
    fdtd.SetGaussExcite(B_F0_HZ, B_FC_HZ)
    # x lo/hi, y lo/hi, z lo/hi -- PEC on z lo (ground), PML_8 everywhere
    # else (matches rfx's own BoundarySpec exactly; no MUR in Stage B).
    fdtd.SetBoundaryCond(["PML_8", "PML_8", "PML_8", "PML_8", "PEC", "PML_8"])

    csx = ContinuousStructure()
    fdtd.SetCSX(csx)
    mesh = csx.GetGrid()
    mesh.SetDeltaUnit(unit)

    resolution = dx
    # Thirds-rule Y refinement at the trace edges (module docstring DELTA
    # LIST item 3 -- the MSL_NotchFilter.py tutorial's own convention,
    # applied here for Stage B's phase-precision goal).
    third_mesh = np.array([2.0 * resolution / 3.0, -resolution / 3.0]) / 4.0

    x_lines = np.arange(x0, x1 + 0.5 * dx, dx)
    mesh.AddLine("x", x_lines)

    mesh.AddLine("y", [y0, y1])
    mesh.AddLine("y", trace_y_lo + third_mesh)
    mesh.AddLine("y", trace_y_hi + third_mesh)
    y_lines_bulk = np.arange(y0, y1 + 0.5 * dx, dx)
    mesh.AddLine("y", y_lines_bulk)
    mesh.SmoothMeshLines("y", resolution / 4.0, 1.4)

    # m6 fix: explicit substrate-top line (z=h_sub), not left to an
    # unguided uniform arange (see _stage_b_substrate_z_mesh docstring).
    z_lines_sub, n_sub = _stage_b_substrate_z_mesh(h_sub, dx)
    assert n_sub == round(B_H_SUB_M / B_DX_M), (
        f"Stage B substrate rasterized cell count drifted: got {n_sub}, "
        f"expected round(h_sub/dx)={round(B_H_SUB_M / B_DX_M)} (#325 class)"
    )
    z_lines_air = np.arange(h_sub, z1 + 0.5 * dx, dx)
    mesh.AddLine("z", z_lines_sub)
    mesh.AddLine("z", z_lines_air)

    # Substrate (dielectric only) extended through the x/y-PML; the TRACE
    # (conductor) is NOT (M3 fix -- see module docstring "Port topology").
    substrate = csx.AddMaterial("ro4350b", epsilon=B_EPS_R)
    substrate.AddBox([x0, y0, 0.0], [x1, y1, h_sub])

    pec = csx.AddMetal("copper")
    # NEW-3 fix (review 2026-08-04): the trace span and MeasPlaneShift
    # targets are now sourced from the PURE, openEMS-free
    # _stage_b_port_placement (wired, not a second hand-copy) so the
    # header test can assert on the SAME numbers this function actually
    # uses, instead of grepping the source text.
    placement = _stage_b_port_placement(layout)
    feed_x0 = placement["trace_x_start_m"] / unit
    feed_x1 = placement["trace_x_stop_m"] / unit
    port_w = B_PORT_W_CELLS * dx

    # M3 fix: the trace spans EXACTLY feed_x0..feed_x1 -- thru_openems.py's
    # own single-AddBox span (X1..X2, each port's own `start`) -- with
    # NOTHING beyond either port toward the PML (no through-PML
    # continuation of the conductor; see module docstring "Port topology"
    # for the parallel-impedance defect this fixes).
    pec.AddBox([feed_x0, trace_y_lo, h_sub], [feed_x1, trace_y_hi, h_sub + dx], priority=10)

    # m5 fix: MeasPlaneShift set EXPLICITLY to this fixture's own
    # ref_plane_shift target (2.5mm here, same "unit" as ref_plane_shift
    # in _run_stage_b's own CalcPort call) -- NOT the class default (half
    # the port's own 300um span, 150um/3 cells from the excitation+
    # Feed_R -- near-field contaminated). See module docstring DELTA LIST
    # item 5.
    measplane_target0_units = placement["measplane_shift_target_port0_m"] / unit
    measplane_target1_units = placement["measplane_shift_target_port1_m"] / unit

    port0_metal = csx.AddMetal("port0_metal")
    port0 = MSLPort(
        csx, port_nr=1, metal_prop=port0_metal,
        start=[feed_x0, trace_y_lo, h_sub], stop=[feed_x0 + port_w, trace_y_hi, 0.0],
        prop_dir="x", exc_dir="z", excite=1.0, Feed_R=50.0,
        MeasPlaneShift=measplane_target0_units, priority=10,
    )
    port1_metal = csx.AddMetal("port1_metal")
    port1 = MSLPort(
        csx, port_nr=2, metal_prop=port1_metal,
        start=[feed_x1, trace_y_lo, h_sub], stop=[feed_x1 - port_w, trace_y_hi, 0.0],
        prop_dir="x", exc_dir="z", excite=0.0, Feed_R=50.0,
        MeasPlaneShift=measplane_target1_units, priority=10,
    )

    # n8 fix: assert the ports' own `start` (what ref_plane_shift/
    # MeasPlaneShift are BOTH computed relative to, module docstring
    # CONVENTION NOTE part (c)) still equals feed_x0/feed_x1 -- a silent
    # coupling: _stage_b_layout computes ref_plane_shift assuming
    # `start[prop] == feed_x`, but nothing enforced that invariant at the
    # point the ports are actually built, ~250 lines away.
    assert abs(float(port0.start[0]) - feed_x0) < 1e-6, (
        "Stage B port0 start drifted from the ref_plane_shift/"
        "MeasPlaneShift target (250-line silent coupling, n8 regression)"
    )
    assert abs(float(port1.start[0]) - feed_x1) < 1e-6, (
        "Stage B port1 start drifted from the ref_plane_shift/"
        "MeasPlaneShift target (250-line silent coupling, n8 regression)"
    )

    # NEW-1/NEW-3 fix (review 2026-08-04): read openEMS's OWN, REAL,
    # mesh-line-snapped measplane_shift (available immediately after
    # MSLPort.__init__ -- see _predict_measplane_snap's own docstring)
    # and cross-check it against the PURE prediction above (an
    # AssertionError here means Stage B's own "uniform, start-aligned
    # x-mesh" assumption broke -- e.g. a future edit adds x-refinement --
    # not a physics finding). Compute the REAL effective CalcPort shift
    # (ref_plane_shift - measured measplane_shift) so the artifact records
    # what ref_plane_shift ACTUALLY did on this run, not just what this
    # script predicted it would do.
    measplane_real0_m = float(port0.measplane_shift) * unit
    measplane_real1_m = float(port1.measplane_shift) * unit
    assert abs(measplane_real0_m - placement["measplane_shift_predicted_port0_m"]) < 1e-9, (
        f"Stage B port0's REAL measplane_shift ({measplane_real0_m} m) does "
        f"not match the pure-arithmetic prediction "
        f"({placement['measplane_shift_predicted_port0_m']} m) -- the "
        f"uniform-grid assumption _predict_measplane_snap relies on broke"
    )
    assert abs(measplane_real1_m - placement["measplane_shift_predicted_port1_m"]) < 1e-9, (
        f"Stage B port1's REAL measplane_shift ({measplane_real1_m} m) does "
        f"not match the pure-arithmetic prediction "
        f"({placement['measplane_shift_predicted_port1_m']} m) -- the "
        f"uniform-grid assumption _predict_measplane_snap relies on broke"
    )

    port_info = dict(placement)
    port_info["measplane_shift_real_port0_m"] = measplane_real0_m
    port_info["measplane_shift_real_port1_m"] = measplane_real1_m
    port_info["effective_shift_real_port0_m"] = (
        placement["ref_plane_shift_port0_m"] - measplane_real0_m
    )
    port_info["effective_shift_real_port1_m"] = (
        placement["ref_plane_shift_port1_m"] - measplane_real1_m
    )

    return fdtd, port0, port1, port_info


def _run_stage_b(*, sim_root: str, threads: int, nrts: int, end_criteria: float,
                 rfx_fixture: dict) -> dict:
    ContinuousStructure, openEMS, MSLPort = _import_openems()
    layout = _stage_b_layout(rfx_fixture)

    sim_dir = os.path.join(sim_root, "stage_b_thru")
    smoke_dir = os.path.join(sim_root, "stage_b_thru_smoke")

    smoke_fdtd, _p0, _p1, _pinfo = _build_stage_b(
        ContinuousStructure, openEMS, MSLPort, layout, nrts=200, end_criteria=0.0)
    smoke_log = _run_openems_capturing_stdout(smoke_fdtd, smoke_dir, threads=threads)
    _scan_stdout_for_bad_patterns(smoke_log, "stage_b_smoke")

    fdtd, port0, port1, port_info = _build_stage_b(
        ContinuousStructure, openEMS, MSLPort, layout, nrts=nrts, end_criteria=end_criteria)

    t0 = time.time()
    real_log = _run_openems_capturing_stdout(fdtd, sim_dir, threads=threads)
    _scan_stdout_for_bad_patterns(real_log, "stage_b")
    elapsed = time.time() - t0
    end_criteria_not_reached = "reached before the end-criteria of" in real_log

    freqs_hz = np.asarray(rfx_fixture["freqs_hz"], dtype=float)
    unit = 1.0e-6
    # NEW-1 fix: ref_plane_shift is the SAME target port_info already
    # recorded as measplane_shift_target -- on this fixture the two are
    # identical by construction (see _stage_b_port_placement's own
    # docstring), so this call's own rotation is a measured no-op
    # (port_info["effective_shift_real_port{0,1}_m"] ~= 0.0). The
    # argument is still passed -- the code path is exercised, not
    # skipped -- for a geometry where the target would NOT land exactly
    # on-grid.
    ref_shift0_units = port_info["ref_plane_shift_port0_m"] / unit
    ref_shift1_units = port_info["ref_plane_shift_port1_m"] / unit

    port0.CalcPort(sim_dir, freqs_hz, ref_plane_shift=ref_shift0_units)
    port1.CalcPort(sim_dir, freqs_hz, ref_plane_shift=ref_shift1_units)

    inc_peak, n_samples = _check_excitation_and_trace(port0, sim_dir, "stage_b", channel="uf_inc")
    truncated = bool(nrts > 0 and n_samples >= nrts)

    s11 = np.asarray(port0.uf_ref, dtype=np.complex128) / np.asarray(port0.uf_inc, dtype=np.complex128)
    s21 = np.asarray(port1.uf_ref, dtype=np.complex128) / np.asarray(port0.uf_inc, dtype=np.complex128)
    beta_port0 = np.asarray(getattr(port0, "beta", np.full_like(freqs_hz, np.nan, dtype=complex)), dtype=np.complex128)
    beta_port1 = np.asarray(getattr(port1, "beta", np.full_like(freqs_hz, np.nan, dtype=complex)), dtype=np.complex128)

    partial_data = {
        "freqs_hz": freqs_hz.tolist(),
        "s11": [[float(c.real), float(c.imag)] for c in s11],
        "s21": [[float(c.real), float(c.imag)] for c in s21],
        "s11_mag": np.abs(s11).tolist(), "s21_mag": np.abs(s21).tolist(),
        "beta_port0": [[float(c.real), float(c.imag)] for c in beta_port0],
        "beta_port1": [[float(c.real), float(c.imag)] for c in beta_port1],
        "port_info": port_info,
        "max_uf_inc": inc_peak, "n_trace_samples": n_samples, "nrts_cap": nrts,
        "truncated_suspected": truncated, "elapsed_s": round(elapsed, 1),
        "end_criteria_not_reached": end_criteria_not_reached,
    }

    try:
        _non_physical_guard(np.abs(s11), "stage_b_s11")
        _non_physical_guard(np.abs(s21), "stage_b_s21")
        passivity = _passivity_witness(s11, s21, "stage_b")

        beta_openems = 0.5 * (beta_port0 + beta_port1)
        self_consistency_openems = _self_consistency_witness(
            freqs_hz, s21, beta_openems, l12_m=layout["l12_m"],
            mag_band=B_S21_MAG_BAND, phase_tol_deg=B_PHASE_TOL_DEG,
            gd_tol_ps=B_GD_TOL_PS, label="stage_b_openems_self_consistency",
        )
    except RuntimeError as exc:
        exc.partial_stage_b_data = partial_data
        raise

    # --- Cross-solver comparison (REPORTED, not gated -- module docstring
    # "WHAT IS GATED vs REPORTED"). ---
    s21_rfx = np.asarray([complex(re, im) for re, im in rfx_fixture["s21"]], dtype=np.complex128)
    beta_rfx = np.asarray([complex(re, im) for re, im in rfx_fixture["beta_first_port"]], dtype=np.complex128)
    assert s21_rfx.shape == freqs_hz.shape, "rfx fixture S21 length mismatch vs freqs_hz"

    phase_rfx = np.unwrap(np.angle(s21_rfx))
    phase_openems = np.unwrap(np.angle(s21))
    raw_phase_diff_deg = np.degrees(np.angle(np.exp(1j * (phase_rfx - phase_openems))))

    beta_ratio = np.real(beta_rfx) / np.where(np.real(beta_openems) != 0, np.real(beta_openems), np.nan)
    dispersion_predicted_diff_rad = (np.real(beta_openems) - np.real(beta_rfx)) * layout["l12_m"]
    residual_after_dispersion_deg = np.degrees(
        np.angle(np.exp(1j * (np.radians(raw_phase_diff_deg) - dispersion_predicted_diff_rad)))
    )

    cross_solver_report = {
        "l12_m": layout["l12_m"],
        "beta_rfx_real": np.real(beta_rfx).tolist(),
        "beta_openems_real": np.real(beta_openems).tolist(),
        "beta_ratio_rfx_over_openems": beta_ratio.tolist(),
        "raw_phase_diff_deg": raw_phase_diff_deg.tolist(),
        "residual_phase_diff_after_dispersion_deg": residual_after_dispersion_deg.tolist(),
        "s21_mag_rfx": np.abs(s21_rfx).tolist(),
        "s21_mag_openems": np.abs(s21).tolist(),
    }

    self_consistency_rfx_report = None
    try:
        self_consistency_rfx_report = _self_consistency_witness(
            freqs_hz, s21_rfx, beta_rfx, l12_m=layout["l12_m"],
            mag_band=B_S21_MAG_BAND, phase_tol_deg=B_PHASE_TOL_DEG,
            gd_tol_ps=B_GD_TOL_PS, label="stage_b_rfx_self_consistency",
        )
    except RuntimeError as exc:
        # rfx's own self-consistency is REPORTED alongside openEMS's (both
        # solvers' referral math is being demonstrated), but it must not
        # abort Stage B if the rfx side alone is out of band -- record the
        # failure text instead of raising, so the artifact still completes.
        self_consistency_rfx_report = {"passed": False, "error": str(exc)}

    phase21, gd21_s = np.unwrap(np.angle(s21)), None
    omega = 2.0 * np.pi * freqs_hz
    gd21_s = -np.gradient(phase21, omega)

    sanity_passed = bool(
        not truncated and passivity["passed"] and self_consistency_openems["passed"]
    )

    return {
        "freqs_hz": freqs_hz.tolist(),
        "s11": [[float(c.real), float(c.imag)] for c in s11],
        "s21": [[float(c.real), float(c.imag)] for c in s21],
        "s11_mag": np.abs(s11).tolist(), "s21_mag": np.abs(s21).tolist(),
        "s21_phase_rad_unwrapped": phase21.tolist(),
        "group_delay_ps": (gd21_s * 1e12).tolist(),
        "beta_port0": [[float(c.real), float(c.imag)] for c in beta_port0],
        "beta_port1": [[float(c.real), float(c.imag)] for c in beta_port1],
        "layout": layout,
        # NEW-1(b) fix (review 2026-08-04): the computed per-port
        # ref_plane_shift - measplane_shift (both predicted AND the REAL,
        # openEMS-measured value) so a reviewer sees the 0.000 directly
        # in the artifact rather than having to trust the docstring.
        "port_info": port_info,
        "passivity": passivity,
        "self_consistency_openems": self_consistency_openems,
        "self_consistency_rfx": self_consistency_rfx_report,
        "cross_solver_report": cross_solver_report,
        "max_uf_inc": inc_peak, "n_trace_samples": n_samples, "nrts_cap": nrts,
        "truncated_suspected": truncated, "elapsed_s": round(elapsed, 1),
        "end_criteria_not_reached": end_criteria_not_reached,
        "sanity_passed": sanity_passed,
    }


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--output", default=".omx/msl-phase-referee/openems_msl_phase_referee.json")
    p.add_argument("--sim-root", default="/tmp/openems_msl_phase_referee")
    p.add_argument("--threads", type=int, default=16)
    p.add_argument("--nrts", type=int, default=300000, help="Stage B only")
    p.add_argument("--end-criteria", type=float, default=1e-4, help="Stage B only")
    p.add_argument("--rfx-fixture", default=RFX_FIXTURE_PATH)
    p.add_argument("--skip-stage-b", action="store_true")
    args = p.parse_args(argv)

    out_path = os.path.abspath(args.output)

    try:
        rfx_fixture = _load_rfx_fixture(args.rfx_fixture)
        _stage_b_layout(rfx_fixture)  # pure-arithmetic check FIRST, before openEMS
    except AssertionError as exc:
        print(f"CONFIG ERROR: Stage B layout assertion failed: {exc}", file=sys.stderr)
        return 3
    except FileNotFoundError as exc:
        print(f"CONFIG ERROR: {exc}", file=sys.stderr)
        return 3

    try:
        _import_openems()
    except ImportError as exc:
        print(f"SKIP: openEMS Python bindings not importable ({exc}).\n"
              "  This script is VESSL-only (source-built openEMS); see "
              "scripts/vessl_msl_phase_referee.yaml.", file=sys.stderr)
        return 2

    print("=" * 78)
    print("openEMS external referee -- rfx issue #490 lane 2 (MSL phase)")
    print("COMPARATOR LEG ONLY. Stage A = faithful MSL_NotchFilter.py port.")
    print("See module docstring for the full scope fence, delta list, convention note.")
    print("=" * 78)
    print(f"\nDeclared question:\n  {DECLARED_QUESTION}")

    t_start = time.time()
    sim_root = os.path.abspath(args.sim_root)

    try:
        print("\n--- Stage A: reproduce-gate (MSL_NotchFilter.py, faithful port) ---")
        stage_a = _run_stage_a_reproduce_gate(sim_root=sim_root, threads=args.threads)
        print(f"  f_notch: measured={stage_a['f_notch_hz']/1e9:.4f} GHz "
              f"expected={F_NOTCH_AN_HZ/1e9:.4f} GHz dev={stage_a['f_notch_dev_pct']:.2f}%")
        print(f"  Stage A passed: {stage_a['passed']}")

        stage_b = None
        if stage_a["passed"] and not args.skip_stage_b:
            print("\n--- Stage B: rfx-matched thru-line (ref_plane_shift referral) ---")
            stage_b = _run_stage_b(
                sim_root=sim_root, threads=args.threads, nrts=args.nrts,
                end_criteria=args.end_criteria, rfx_fixture=rfx_fixture,
            )
            print(f"  |S21| band: {min(stage_b['s21_mag']):.4f} - {max(stage_b['s21_mag']):.4f}")
            print(f"  openEMS self-consistency passed: {stage_b['self_consistency_openems']['passed']}")
            print(f"  rfx self-consistency (reported): "
                  f"{stage_b['self_consistency_rfx']['passed']}")
            print(f"  sanity_passed: {stage_b['sanity_passed']}")
        elif not stage_a["passed"]:
            print("\nStage A FAILED its reproduce-gate -- skipping Stage B "
                  "(external_solver_comparator.md: 'only then swap in the "
                  "target geometry').")
    except AssertionError as exc:
        print(f"\nCONFIG ERROR (internal script bug, not a physics finding): {exc}", file=sys.stderr)
        return 3
    except RuntimeError as exc:
        print(f"\nSELF-CHECK / PHYSICS-GATE FAILED: {exc}", file=sys.stderr)
        elapsed_total = time.time() - t_start
        artifact = {
            "issue": 490, "stage": "lane 2 (external openEMS referee)",
            "scope": "comparator leg only",
            "error": str(exc), "elapsed_s": round(elapsed_total, 1),
        }
        partial = getattr(exc, "partial_stage_b_data", None)
        if partial is not None:
            artifact["stage_b_partial"] = partial
        os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
        with open(out_path, "w") as f:
            json.dump(artifact, f, indent=2)
        return 1

    overall_passed = bool(
        stage_a["passed"] and (stage_b is None or stage_b["sanity_passed"])
    )

    elapsed_total = time.time() - t_start
    artifact = {
        "issue": 490, "stage": "lane 2 (external openEMS referee)",
        "scope": "comparator leg only -- brackets, does not judge rfx's own numbers",
        "declared_question": DECLARED_QUESTION,
        "must_move_when_validated": MUST_MOVE_WHEN_VALIDATED,
        "reproduce_gate_record": REPRODUCE_GATE_RECORD,
        "stage_a": stage_a, "stage_b": stage_b,
        "overall_passed": overall_passed, "elapsed_s": round(elapsed_total, 1),
    }

    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    with open(out_path, "w") as f:
        json.dump(artifact, f, indent=2)
    print(f"\n=== Written to {out_path} ===")

    print("\n" + "=" * 78)
    print(f"overall_passed={overall_passed} (self-checks only -- NOT a "
          f"verdict on rfx vs openEMS phase agreement)")
    print("=" * 78)

    return 0 if overall_passed else 1


if __name__ == "__main__":
    sys.exit(main())
